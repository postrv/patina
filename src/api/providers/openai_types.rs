/// A tool definition in the OpenAI format.
///
/// Tools are wrapped in a `type: "function"` envelope with the function
/// definition inside.
///
/// # Examples
///
/// ```rust
/// use patina::api::providers::openai_types::{OpenAiTool, OpenAiFunctionDef};
/// use serde_json::json;
///
/// let tool = OpenAiTool::function(
///     "get_weather",
///     "Get the current weather",
///     json!({"type": "object", "properties": {"location": {"type": "string"}}}),
/// );
/// ```
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct OpenAiTool {
    /// Always `"function"` in the current API.
    #[serde(rename = "type")]
    pub tool_type: String,

    /// The function definition.
    pub function: OpenAiFunctionDef,
}

impl OpenAiTool {
    /// Creates a function tool definition.
    #[must_use]
    pub fn function(
        name: impl Into<String>,
        description: impl Into<String>,
        parameters: Value,
    ) -> Self {
        Self {
            tool_type: "function".to_string(),
            function: OpenAiFunctionDef {
                name: name.into(),
                description: Some(description.into()),
                parameters: Some(parameters),
            },
        }
    }
}

/// Function definition within a tool.
///
/// Describes the function name, what it does, and its parameter schema.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct OpenAiFunctionDef {
    /// The name of the function.
    pub name: String,

    /// Description of what the function does.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub description: Option<String>,

    /// JSON Schema for the function's parameters.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub parameters: Option<Value>,
}

