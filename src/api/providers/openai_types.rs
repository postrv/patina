/// Tool choice constraint for the API request.
///
/// Controls how the model selects tools. Can be a keyword string
/// (`"none"`, `"auto"`, `"required"`) or a specific function.
///
/// # Examples
///
/// ```rust
/// use patina::api::providers::openai_types::OpenAiToolChoice;
///
/// // Let the model decide
/// let auto = OpenAiToolChoice::auto();
/// let json = serde_json::to_string(&auto).unwrap();
/// assert_eq!(json, "\"auto\"");
///
/// // Require a specific function
/// let specific = OpenAiToolChoice::function("get_weather");
/// let json = serde_json::to_string(&specific).unwrap();
/// assert!(json.contains("get_weather"));
/// ```
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
#[serde(untagged)]
pub enum OpenAiToolChoice {
    /// A keyword choice: `"none"`, `"auto"`, or `"required"`.
    Keyword(String),

    /// A specific function that the model must call.
    Named(OpenAiNamedToolChoice),
}

impl OpenAiToolChoice {
    /// Disables tool use entirely.
    #[must_use]
    pub fn none() -> Self {
        Self::Keyword("none".to_string())
    }

    /// Lets the model decide whether to use tools.
    #[must_use]
    pub fn auto() -> Self {
        Self::Keyword("auto".to_string())
    }

    /// Requires the model to use at least one tool.
    #[must_use]
    pub fn required() -> Self {
        Self::Keyword("required".to_string())
    }

    /// Requires the model to call a specific function.
    #[must_use]
    pub fn function(name: impl Into<String>) -> Self {
        Self::Named(OpenAiNamedToolChoice {
            tool_type: "function".to_string(),
            function: OpenAiToolChoiceFunction { name: name.into() },
        })
    }
}

/// A named tool choice specifying a particular function.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct OpenAiNamedToolChoice {
    /// Always `"function"`.
    #[serde(rename = "type")]
    pub tool_type: String,

    /// The function to require.
    pub function: OpenAiToolChoiceFunction,
}

/// Function name within a named tool choice.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct OpenAiToolChoiceFunction {
    /// The name of the function the model must call.
    pub name: String,
}

