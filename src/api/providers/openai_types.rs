/// A complete (non-streaming) response from the Chat Completions API.
///
/// Contains one or more choices with the model's response.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct OpenAiResponse {
    /// Unique identifier for this completion.
    pub id: String,

    /// Object type, always `"chat.completion"`.
    pub object: String,

    /// Unix timestamp of when the completion was created.
    pub created: u64,

    /// The model that generated the completion.
    pub model: String,

    /// The list of completion choices.
    pub choices: Vec<OpenAiChoice>,

    /// Token usage statistics.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub usage: Option<OpenAiUsage>,
}

/// A single choice in a non-streaming response.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct OpenAiChoice {
    /// The index of this choice in the choices array.
    pub index: u32,

    /// The assistant's response message.
    pub message: OpenAiMessage,

    /// The reason the model stopped generating.
    pub finish_reason: OpenAiFinishReason,
}

/// Token usage statistics.
///
/// # Examples
///
/// ```rust
/// use patina::api::providers::openai_types::OpenAiUsage;
///
/// let usage = OpenAiUsage {
///     prompt_tokens: 10,
///     completion_tokens: 20,
///     total_tokens: 30,
/// };
/// assert_eq!(usage.total_tokens, usage.prompt_tokens + usage.completion_tokens);
/// ```
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct OpenAiUsage {
    /// Number of tokens in the prompt.
    pub prompt_tokens: u32,

    /// Number of tokens in the generated completion.
    pub completion_tokens: u32,

    /// Total tokens used (prompt + completion).
    pub total_tokens: u32,
}

