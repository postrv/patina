/// A message in the OpenAI Chat Completions format.
///
/// This unified struct represents messages for all roles. Optional fields
/// are used depending on the role:
///
/// - **System**: `content` only
/// - **User**: `content` only (or `name` for multi-user scenarios)
/// - **Assistant**: `content` and/or `tool_calls`
/// - **Tool**: `content` and `tool_call_id`
///
/// # Examples
///
/// ```rust
/// use patina::api::providers::openai_types::OpenAiMessage;
///
/// // Simple user message
/// let msg = OpenAiMessage::user("What's the weather?");
///
/// // System instruction
/// let sys = OpenAiMessage::system("You are a helpful assistant.");
/// ```
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct OpenAiMessage {
    /// The role of the message author.
    pub role: OpenAiRole,

    /// The content of the message. `None` for assistant messages that only
    /// contain tool calls.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub content: Option<String>,

    /// An optional name for the participant (for multi-user conversations).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub name: Option<String>,

    /// Tool calls generated by the model (assistant messages only).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub tool_calls: Option<Vec<OpenAiToolCall>>,

    /// The ID of the tool call this message responds to (tool messages only).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub tool_call_id: Option<String>,
}

impl OpenAiMessage {
    /// Creates a system message.
    #[must_use]
    pub fn system(content: impl Into<String>) -> Self {
        Self {
            role: OpenAiRole::System,
            content: Some(content.into()),
            name: None,
            tool_calls: None,
            tool_call_id: None,
        }
    }

    /// Creates a user message.
    #[must_use]
    pub fn user(content: impl Into<String>) -> Self {
        Self {
            role: OpenAiRole::User,
            content: Some(content.into()),
            name: None,
            tool_calls: None,
            tool_call_id: None,
        }
    }

    /// Creates an assistant message with text content.
    #[must_use]
    pub fn assistant(content: impl Into<String>) -> Self {
        Self {
            role: OpenAiRole::Assistant,
            content: Some(content.into()),
            name: None,
            tool_calls: None,
            tool_call_id: None,
        }
    }

    /// Creates an assistant message with tool calls (content is null).
    #[must_use]
    pub fn assistant_with_tool_calls(tool_calls: Vec<OpenAiToolCall>) -> Self {
        Self {
            role: OpenAiRole::Assistant,
            content: None,
            name: None,
            tool_calls: Some(tool_calls),
            tool_call_id: None,
        }
    }

    /// Creates a tool result message.
    #[must_use]
    pub fn tool(tool_call_id: impl Into<String>, content: impl Into<String>) -> Self {
        Self {
            role: OpenAiRole::Tool,
            content: Some(content.into()),
            name: None,
            tool_calls: None,
            tool_call_id: Some(tool_call_id.into()),
        }
    }
}

/// A tool call generated by the model.
///
/// In the OpenAI format, tool calls always have `type: "function"`.
/// The `function` field contains the function name and arguments as a
/// JSON-encoded string.
///
/// # Examples
///
/// ```rust
/// use patina::api::providers::openai_types::{OpenAiToolCall, OpenAiFunctionCall};
///
/// let call = OpenAiToolCall {
///     id: "call_abc123".to_string(),
///     call_type: "function".to_string(),
///     function: OpenAiFunctionCall {
///         name: "get_weather".to_string(),
///         arguments: r#"{"location":"Boston"}"#.to_string(),
///     },
/// };
/// assert_eq!(call.function.name, "get_weather");
/// ```
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct OpenAiToolCall {
    /// Unique identifier for this tool call.
    pub id: String,

    /// Always `"function"` in the current API.
    #[serde(rename = "type")]
    pub call_type: String,

    /// The function to call with its arguments.
    pub function: OpenAiFunctionCall,
}

impl OpenAiToolCall {
    /// Creates a new function tool call.
    ///
    /// # Arguments
    ///
    /// * `id` - Unique call identifier (e.g., "call_abc123")
    /// * `name` - Function name to call
    /// * `arguments` - JSON-encoded string of arguments
    #[must_use]
    pub fn new(
        id: impl Into<String>,
        name: impl Into<String>,
        arguments: impl Into<String>,
    ) -> Self {
        Self {
            id: id.into(),
            call_type: "function".to_string(),
            function: OpenAiFunctionCall {
                name: name.into(),
                arguments: arguments.into(),
            },
        }
    }
}

/// Function call details within a tool call.
///
/// Note that `arguments` is a JSON-encoded **string**, not a parsed JSON
/// object. This matches the OpenAI API specification where arguments are
/// streamed as string fragments that must be concatenated before parsing.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct OpenAiFunctionCall {
    /// The name of the function to call.
    pub name: String,

    /// The arguments as a JSON-encoded string.
    pub arguments: String,
}

