//! OpenAI Chat Completions API message types.
//!
//! These types represent the OpenAI-format request and response structures
//! used by OpenRouter and other OpenAI-compatible APIs. They are distinct
//! from Anthropic's message format and require bidirectional translation.
//!
//! # Overview
//!
//! The OpenAI Chat Completions API uses a different message structure than
//! Anthropic. Key differences:
//!
//! - Messages use `role` field with `system`/`user`/`assistant`/`tool` values
//! - Tool calls use `function` with `arguments` as a JSON **string** (not parsed object)
//! - Streaming uses `delta` objects within `choices` arrays
//! - Finish reasons use `stop`/`tool_calls`/`length` instead of Anthropic's `end_turn`/`tool_use`/`max_tokens`
//!
//! # References
//!
//! - [OpenAI Chat Completions API](https://platform.openai.com/docs/api-reference/chat)
//! - [OpenRouter API](https://openrouter.ai/docs)
//!
//! # Example
//!
//! ```rust
//! use patina::api::providers::openai_types::{OpenAiMessage, OpenAiRole};
//!
//! let msg = OpenAiMessage::user("Hello, how are you?");
//! assert_eq!(msg.role, OpenAiRole::User);
//! assert_eq!(msg.content.as_deref(), Some("Hello, how are you?"));
//! ```

use serde::{Deserialize, Serialize};
use serde_json::Value;

// =============================================================================
// Roles and Finish Reasons
// =============================================================================

/// Message role in the OpenAI Chat Completions API.
///
/// Each message in a conversation has a role that determines how the API
/// interprets it.
///
/// # Examples
///
/// ```rust
/// use patina::api::providers::openai_types::OpenAiRole;
///
/// let role = OpenAiRole::Assistant;
/// let json = serde_json::to_string(&role).unwrap();
/// assert_eq!(json, "\"assistant\"");
/// ```
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum OpenAiRole {
    /// System instructions that guide the model's behavior.
    System,
    /// User input in the conversation.
    User,
    /// Model-generated responses.
    Assistant,
    /// Tool execution results returned to the model.
    Tool,
}

/// Reason the model stopped generating tokens.
///
/// Determines whether the client should take action (e.g., execute tools)
/// or present the response to the user.
///
/// # Examples
///
/// ```rust
/// use patina::api::providers::openai_types::OpenAiFinishReason;
///
/// let reason: OpenAiFinishReason = serde_json::from_str("\"stop\"").unwrap();
/// assert_eq!(reason, OpenAiFinishReason::Stop);
/// ```
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum OpenAiFinishReason {
    /// The model finished generating naturally.
    Stop,
    /// The model wants to call one or more tools.
    ToolCalls,
    /// The response hit the token limit.
    Length,
    /// Content was filtered by the provider's safety system.
    ContentFilter,
}

