/// A Server-Sent Event chunk from the streaming Chat Completions API.
///
/// Each chunk contains partial response data in the `choices` array.
/// The `delta` field within each choice contains the incremental update.
///
/// # Examples
///
/// ```rust
/// use patina::api::providers::openai_types::OpenAiStreamChunk;
///
/// let json = r#"{
///     "id": "chatcmpl-abc",
///     "object": "chat.completion.chunk",
///     "created": 1694268190,
///     "model": "gpt-4",
///     "choices": [{
///         "index": 0,
///         "delta": {"content": "Hello"},
///         "finish_reason": null
///     }]
/// }"#;
///
/// let chunk: OpenAiStreamChunk = serde_json::from_str(json).unwrap();
/// assert_eq!(chunk.choices[0].delta.content.as_deref(), Some("Hello"));
/// ```
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct OpenAiStreamChunk {
    /// Unique identifier for this completion (shared across all chunks).
    pub id: String,

    /// Object type, always `"chat.completion.chunk"`.
    pub object: String,

    /// Unix timestamp of when the completion was created.
    pub created: u64,

    /// The model that generated the completion.
    pub model: String,

    /// The list of streaming choices (usually one).
    pub choices: Vec<OpenAiStreamChoice>,

    /// Token usage (only present in the final chunk if requested).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub usage: Option<OpenAiUsage>,
}

/// A single choice in a streaming response chunk.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct OpenAiStreamChoice {
    /// The index of this choice.
    pub index: u32,

    /// The incremental update for this choice.
    pub delta: OpenAiDelta,

    /// The finish reason, present only in the final chunk.
    pub finish_reason: Option<OpenAiFinishReason>,
}

/// Incremental content in a streaming choice.
///
/// Each delta can contain a subset of message fields. The first delta
/// typically contains `role`, subsequent deltas contain `content` or
/// `tool_calls`, and the final delta is empty with `finish_reason` set.
#[derive(Debug, Clone, Default, Serialize, Deserialize, PartialEq)]
pub struct OpenAiDelta {
    /// The role (present only in the first chunk).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub role: Option<OpenAiRole>,

    /// Text content fragment.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub content: Option<String>,

    /// Partial tool calls being streamed.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub tool_calls: Option<Vec<OpenAiToolCallDelta>>,
}

/// A partial tool call in a streaming delta.
///
/// The first delta for a tool call contains `id`, `type`, and the function
/// `name`. Subsequent deltas contain only `index` and argument fragments.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct OpenAiToolCallDelta {
    /// Index of this tool call (for correlating across chunks).
    pub index: u32,

    /// The tool call ID (present only in the first chunk for this call).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub id: Option<String>,

    /// Always `"function"` (present only in the first chunk).
    #[serde(rename = "type", default, skip_serializing_if = "Option::is_none")]
    pub call_type: Option<String>,

    /// Partial function details.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub function: Option<OpenAiFunctionCallDelta>,
}

/// Partial function call details in a streaming delta.
///
/// In the first chunk, `name` is present. In subsequent chunks,
/// only `arguments` fragments are sent.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct OpenAiFunctionCallDelta {
    /// The function name (present only in the first chunk).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub name: Option<String>,

    /// A fragment of the JSON-encoded arguments string.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub arguments: Option<String>,
}

